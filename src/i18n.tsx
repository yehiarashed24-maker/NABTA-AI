interface I18nContextType {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
  isRtl: boolean;
  currentOption: LanguageOption;
}

const I18nContext = createContext<I18nContextType | null>(null);

const STORAGE_KEY = "nabta_selected_language";

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Language;
      if (saved && translations[saved]) return saved;
      // Default to Arabic or English based on navigator
      const navLang = navigator.language?.slice(0, 2);
      if (navLang === "ar") return "ar";
      return "en";
    } catch {
      return "en";
    }
  });

  const setLang = (newLang: Language) => {
    setLangState(newLang);
    try {
      localStorage.setItem(STORAGE_KEY, newLang);
    } catch {
      // ignore
    }
  };

  const currentOption = LANGUAGES.find((item) => item.code === lang) || LANGUAGES[1];
  const isRtl = currentOption.direction === "rtl";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = "ltr"; // Keep layout physical (ltr) to prevent breaking
    if (isRtl) {
      document.body.classList.add("rtl");
    } else {
      document.body.classList.remove("rtl");
    }
  }, [lang, isRtl]);

  const t = (key: string, params?: Record<string, string | number>): string => {
    const text = translations[lang]?.[key] || translations["en"]?.[key] || key;
    if (!params) return text;
    return Object.entries(params).reduce((acc, [k, v]) => {
      return acc.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }, text);
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t, isRtl, currentOption }}>
      {children}
    </I18nContext.Provider>
  );
};

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return ctx;
}

export const LanguageSwitcher: React.FC<{
  variant?: "pill" | "header" | "compact" | "sidebar";
  className?: string;
}> = ({ variant = "pill", className = "" }) => {
  const { lang, setLang, currentOption } = useI18n();
  const [dropdownOpen, setDropdownOpen] = useState(false);

  // Quick toggle between Arabic and English if user just clicks, or dropdown on hover/expand
  return (
    <div className={`lang-switcher-container lang-${variant} ${className}`}>
      <button
        type="button"
        className="lang-switcher-btn"
        onClick={() => setDropdownOpen(!dropdownOpen)}
        title="Change Language / تغيير اللغة"
        aria-label="Change language"
      >
        <Globe size={15} className="lang-icon" />
        <span className="lang-label">{currentOption.nativeName}</span>
        <span className="lang-flag">{currentOption.flag}</span>
      </button>

      {dropdownOpen && (
        <>
          <div className="lang-backdrop" onClick={() => setDropdownOpen(false)} />
          <div className="lang-menu">
            {LANGUAGES.map((option) => (
              <button
                key={option.code}
                type="button"
                className={`lang-option ${lang === option.code ? "active" : ""}`}
                onClick={() => {
                  setLang(option.code);
                  setDropdownOpen(false);
                }}
              >
                <span className="option-flag">{option.flag}</span>
                <span className="option-native">{option.nativeName}</span>
                <span className="option-code">{option.label}</span>
              </button>
            ))}
          </div>
        </>
      )}
    </div>
  );
};
